def now() -> datetime:
    """Текущее время в Астане. Везде в боте пользуемся только этой функцией."""
    return datetime.now(TZ)


def game_datetime(game) -> datetime:
    """
    Превращает дату и время игры из базы ('2026-08-18' + '15:30')
    в обычную дату-время по Астане — чтобы сравнивать с now().
    """
    moment = datetime.strptime(
        f"{game['game_date']} {game['game_time']}", "%Y-%m-%d %H:%M"
    )
    return moment.replace(tzinfo=TZ)


