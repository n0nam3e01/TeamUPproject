def clean_letter(text: str):
    """
    Проверяет букву класса, которую написали руками.

    Возвращает букву заглавной или None, если введено что-то не то.
    Правило простое: ровно один символ, и это должна быть буква,
    а не цифра, точка или смайлик.
    """
    letter = (text or "").strip().upper()
    if len(letter) != 1 or not letter.isalpha():
        return None
    return letter


